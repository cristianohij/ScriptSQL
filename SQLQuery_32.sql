SELECT 
    c.tabela AS Tabela_TABCOMP,
    c.atributo AS Coluna_TABCOMP,
    c.tipo AS Tipo_TABCOMP,
    c.precisao AS Precisao_TABCOMP,
    c.escala AS Escala_TABCOMP,
    cols.TABLE_NAME AS Tabela_BD,
    cols.COLUMN_NAME AS Coluna_BD,
    cols.DATA_TYPE AS Tipo_BD,
    cols.NUMERIC_PRECISION AS Precisao_BD,
    cols.NUMERIC_SCALE AS Escala_BD
FROM 
    TABCOMP c
LEFT JOIN 
    INFORMATION_SCHEMA.COLUMNS cols 
    ON c.tabela = cols.TABLE_NAME
    AND c.atributo = cols.COLUMN_NAME
WHERE 
    (c.tipo <> cols.DATA_TYPE 
    OR c.precisao <> cols.NUMERIC_PRECISION
    OR c.escala <> cols.NUMERIC_SCALE)
    AND cols.TABLE_NAME IS NOT NULL
ORDER BY 
    c.tabela, c.atributo;


SELECT 
    t.tabela,
    t.atributo,
    t.tipo AS tipo_tabcomp,
    c.DATA_TYPE AS tipo_real,
    t.precisao AS precisao_tabcomp,
    c.CHARACTER_MAXIMUM_LENGTH AS precisao_real,
    t.escala AS escala_tabcomp,
    c.NUMERIC_SCALE AS escala_real,
    CASE 
        WHEN t.tipo <> c.DATA_TYPE THEN 'Tipo diferente'
        WHEN t.precisao <> c.CHARACTER_MAXIMUM_LENGTH THEN 'Precisão diferente'
        WHEN t.escala <> c.NUMERIC_SCALE THEN 'Escala diferente'
        ELSE 'Correto'
    END AS status_comparacao
FROM TABCOMP t
LEFT JOIN INFORMATION_SCHEMA.COLUMNS c
    ON t.tabela = c.TABLE_NAME
    AND t.atributo = c.COLUMN_NAME
WHERE 
    t.tipo <> c.DATA_TYPE
    OR t.precisao <> c.CHARACTER_MAXIMUM_LENGTH
    OR t.escala <> c.NUMERIC_SCALE
ORDER BY t.tabela, t.atributo;


