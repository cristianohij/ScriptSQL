select TBS067.NFSDESICMS,
       TBS0671.NFSEMPCOD,
       TBS0671.NFSNUM,
       TBS0671.PROCOD,
       NFSPRE,
       NFSPRECUS,
       NFSPRECUS/NFSPRE,
       NFSPDDITE,
       NFSFREITE,
       NFSSEGITE,
       NFSDESITE,
       NFSPRE*NFSQTD,
       NFSPRECUS*NFSQTD,
       NFSPBI,
       NFSPRE*NFSQTD*NFSPBI/100 as 'baseICMS',
       NFSPERICMS,
       NFSPRE*NFSQTD*NFSPBI/100*NFSPERICMS/100 as 'valorICMS',
       NFSPRECUS*NFSQTD-NFSPRE*NFSQTD*NFSPBI/100*NFSPERICMS/100,
       NFSQTDEMB
  from TBS0671 (nolock) join TBS067 (nolock) on TBS0671.NFSEMPCOD=TBS067.NFSEMPCOD and TBS0671.NFSNUM=TBS067.NFSNUM
 where TBS067.NFSDATEMI = '20110916' and TBS0671.NFSNUM in(14837,14844,14863,14873,14879)
 order by TBS0671.NFSNUM

