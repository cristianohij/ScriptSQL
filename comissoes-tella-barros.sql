select TBS067.NFSNUM as 'nf',
       TBS067.NFSDATEMI as 'emissao',
       TBS067.VENCOD as 'cod.vendedor',
       (select VENNOM from TBS004 (nolock) where TBS004.VENCOD=TBS067.VENCOD) as 'nome vendedor',
       TBS067.NFSCLICOD as 'cod.cliente',
       TBS067.NFSCLINOM as 'nome cliente',
       round(sum(dbo.NFSTOTITEST(TBS067.NFSEMPCOD,TBS067.NFSNUM,TBS067.SNEEMPCOD,TBS067.SNESER,TBS0671.NFSITE)),2) as 'valor total',
       case TBS067.NFSCAN
          when 'S' then round(sum(dbo.NFSTOTITEST(TBS067.NFSEMPCOD,TBS067.NFSNUM,TBS067.SNEEMPCOD,TBS067.SNESER,TBS0671.NFSITE)),2)
          else 0 end as 'cancelamento',
       round(dbo.NFSTOTDEV(TBS067.NFSEMPCOD,TBS067.NFSNUM,TBS067.SNEEMPCOD,TBS067.SNESER),2) as 'devolucao',
       round(sum(dbo.NFSTOTITEST(TBS067.NFSEMPCOD,TBS067.NFSNUM,TBS067.SNEEMPCOD,TBS067.SNESER,TBS0671.NFSITE)),2) -
       case TBS067.NFSCAN
          when 'S' then round(sum(dbo.NFSTOTITEST(TBS067.NFSEMPCOD,TBS067.NFSNUM,TBS067.SNEEMPCOD,TBS067.SNESER,TBS0671.NFSITE)),2)
          else 0 end -
       round(dbo.NFSTOTDEV(TBS067.NFSEMPCOD,TBS067.NFSNUM,TBS067.SNEEMPCOD,TBS067.SNESER),2) as 'valor liquido',
       TBS0671.NFSPERCOM as 'comissao',
       round((round(sum(dbo.NFSTOTITEST(TBS067.NFSEMPCOD,TBS067.NFSNUM,TBS067.SNEEMPCOD,TBS067.SNESER,TBS0671.NFSITE)),2) -
        case TBS067.NFSCAN
           when 'S' then round(sum(dbo.NFSTOTITEST(TBS067.NFSEMPCOD,TBS067.NFSNUM,TBS067.SNEEMPCOD,TBS067.SNESER,TBS0671.NFSITE)),2)
           else 0 end -
        round(dbo.NFSTOTDEV(TBS067.NFSEMPCOD,TBS067.NFSNUM,TBS067.SNEEMPCOD,TBS067.SNESER),2))
       *
       TBS0671.NFSPERCOM / 100,2) as 'valor comissao'
  from TBS067 (nolock) join TBS0671 (nolock) on TBS067.NFSEMPCOD=TBS0671.NFSEMPCOD and TBS067.SNEEMPCOD=TBS0671.SNEEMPCOD and TBS067.SNESER=TBS0671.SNESER and
                                                TBS067.NFSNUM=TBS0671.NFSNUM
                       join TBS110 (nolock) on TBS0671.NFSROPEMP=TBS110.ROPEMPCOD and TBS0671.NFSROPREG=TBS110.ROPREG
 where TBS067.NFSDATEMI between '20140401' and '20140430' and
       TBS110.ROPGERCOM='S' --and
--       TBS067.NFSCAN='N'
 group by TBS067.NFSEMPCOD,
          TBS067.SNEEMPCOD,
          TBS067.SNESER,
          TBS067.NFSNUM,
          TBS067.NFSDATEMI,
          TBS067.VENCOD,
          TBS067.NFSCLICOD,
          TBS067.NFSCLINOM,
          TBS067.NFSCAN,
          TBS0671.NFSPERCOM
 order by TBS067.VENCOD,TBS067.NFSDATEMI,TBS067.NFSNUM

