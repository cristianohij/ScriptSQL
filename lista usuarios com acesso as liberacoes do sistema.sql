-- lista usuarios com acesso a liberacao de credito/precos/conferencia
select TBS016.USUCOD,TBS0162.MODNOM,TBS0162.MNUNOM,TBS0191.PRGCOD,TBS0191.PRGEVE,TBS018.PRGDES
  from TBS016 join TBS0162 on TBS016.USUCOD=TBS0162.USUCOD
              join TBS0191 on TBS0162.MNUNOM=TBS0191.MNUNOM
              join TBS018 on TBS0191.PRGCOD=TBS018.PRGCOD
 where TBS0191.PRGCOD in('WYVEN007','WYEST005')