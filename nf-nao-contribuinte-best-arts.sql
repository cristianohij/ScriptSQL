select TBS0671.SNESER,NFSDATEMI,CLIINDIE,TBS0671.NFSNUM,TBS0671.NFSCST
  from TBS0671 (nolock)
       inner join TBS067 (nolock) on TBS067.SNESER=TBS0671.SNESER and TBS067.NFSNUM=TBS0671.NFSNUM
       inner join TBS002 (nolock) on TBS002.CLICOD=TBS067.NFSCLICOD
 where NFSDATEMI >= '20160101' and
       CLIINDIE=9
 order by TBS0671.SNESER,TBS0671.NFSNUM desc

