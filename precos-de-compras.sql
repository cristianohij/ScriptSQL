select *
  from TBS0591 (nolock) join TBS059 (nolock)
       on TBS0591.SERCOD=TBS059.SERCOD and TBS0591.NFETIP=TBS059.NFETIP and TBS0591.NFECOD=TBS059.NFECOD and TBS0591.NFENUM=TBS059.NFENUM
 where NFEDATENT >= '20160101' 

select (NFEPRE*NFEQTD)+NFEVALICMSST+NFEVALIPI2,* from TBS0591 (nolock) where NFETIP='N' and NFENUM=136983 order by NFEITE

select sum((NFEPRE*NFEQTD)+NFEVALICMSST+NFEVALIPI2) from TBS0591 (nolock) where NFETIP='N' and NFENUM=136983 group by NFENUM


select convert(int,subString(convert(char(6),NFEDATENT,112),1,4)),
       convert(int,subString(convert(char(6),NFEDATENT,112),5,2)),
       PROCOD,
       round(avg((NFEPREXML*NFEQTDXML+NFEVALICMSST+NFEPERIPI2)/NFEQTDEMB),2)
  from TBS0591 (nolock) join TBS059 (nolock)
       on TBS0591.SERCOD=TBS059.SERCOD and TBS0591.NFETIP=TBS059.NFETIP and TBS0591.NFECOD=TBS059.NFECOD and TBS0591.NFENUM=TBS059.NFENUM
 where TBS0591.NFETIP='N' and NFEDATENT between '20150101' and '20151231' and
       (NFECST Like('%10') or NFECST Like('%30') or NFECST Like('%70')) and
       NFENOM not like('BEST BAG%') and NFENOM not like('BEST OFFICE%') and NFENOM not like('MISASPEL%') and NFENOM not like('%PAPELYNA%') and NFENOM not like('TANBY%')
 group by
convert(char(6),NFEDATENT,112),PROCOD

 order by TBS0591.SERCOD,TBS0591.NFETIP,TBS0591.NFECOD,TBS0591.NFENUM,TBS0591.NFEITE

