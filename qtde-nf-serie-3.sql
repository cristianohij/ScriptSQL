SELECT 
    CONVERT(CHAR(7), ENFDATEMI, 120) AS AnoMes,
    COUNT(*) AS Qtde_Total,
    COUNT(CASE WHEN SNESER = 3 THEN 1 END) AS Qtde_Serie_3,
    CAST(100.0 * COUNT(CASE WHEN SNESER = 3 THEN 1 END) / COUNT(*) AS DECIMAL(10,2)) AS Perc_Serie_3
FROM TBS080 WITH (NOLOCK)
where ENFDATEMI between '20250101' and '20250930'
GROUP BY CONVERT(CHAR(7), ENFDATEMI, 120)
ORDER BY AnoMes;
