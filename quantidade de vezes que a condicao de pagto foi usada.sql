select TBS067.CPGCOD,TBS008.CPGDES,count(TBS067.CPGCOD),str(sum((NFSPRE-(NFSPRE*NFSPDDITE/100))*NFSQTD),10,2)
  from TBS067 join TBS008 on TBS067.CPGCOD=TBS008.CPGCOD 
              join TBS0671 on TBS067.NFSNUM=TBS0671.NFSNUM
 where NFSDATEMI between('20090501') and ('20090531')
 group by TBS067.CPGCOD,TBS008.CPGDES 