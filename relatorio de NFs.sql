select TBS067.NFSNUM,cast(NFSDATEMI as char(11)) as 'NFSDATEMI',NFSCAN,NFSCLICOD,NFSCLINOM,
       str(sum((NFSPRE-(NFSPRE*NFSPDDITE/100))*NFSQTD)+NFSVALFRE+NFSVALDES+NFSVALSEG,10,2) as 'NFSTOTLIQ',NFSDESICMS,
       str(sum(NFSPBI*((NFSPRE-(NFSPRE*NFSPDDITE/100))*NFSQTD)/100*NFSPERICMS/100),10,2) as 'ICMS'
  from TBS0671 right join TBS067 on TBS0671.NFSNUM=TBS067.NFSNUM
               right join TBS042 on TBS0671.TESCOD=TBS042.TESCOD
 where NFSDATEMI between '2008-05-01' and '2008-05-31' and TBS042.TESCNTVEN='S'
group by TBS067.NFSNUM,NFSDATEMI,NFSCAN,NFSCLICOD,NFSCLINOM,NFSVALFRE,NFSVALDES,NFSVALSEG,NFSDESICMS
order by NFSDATEMI,TBS067.NFSNUM

