select TBS0671.NFSNUM,
       NFSCAN,
       TBS067.NFSDATEMI,
       TBS0671.SNESER,
       NFSCLICOD,
       NFSCLINOM,
       PROCOD,
       NFSPRODES,
       NFSUNI,
       dbo.NFSPRELIQ(TBS0671.NFSEMPCOD,TBS0671.NFSNUM,TBS0671.SNEEMPCOD,TBS0671.SNESER,NFSITE),
       NFSQTD,
       dbo.NFSTOTITE(TBS0671.NFSEMPCOD,TBS0671.NFSNUM,TBS0671.SNEEMPCOD,TBS0671.SNESER,NFSITE)
  from TBS0671 (nolock) join TBS067 (nolock)
                        on TBS0671.NFSEMPCOD=TBS067.NFSEMPCOD and TBS0671.SNEEMPCOD=TBS067.SNEEMPCOD and TBS0671.SNESER=TBS067.SNESER and
                           TBS0671.NFSNUM=TBS067.NFSNUM
 where NFSDATEMI between '20131001' and '20140124' and PROCOD in('6660029','6660213','10390004','10390003','1070029')