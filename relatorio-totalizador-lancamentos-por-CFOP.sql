select NFECFOP,count(*)
  from TBS0591 (nolock) join TBS059 (nolock)
    on TBS0591.NFEEMPCOD=TBS059.NFEEMPCOD and TBS0591.NFETIP=TBS059.NFETIP and TBS0591.SERCOD=TBS059.SERCOD and TBS0591.NFECOD=TBS059.NFECOD and TBS0591.NFENUM=TBS059.NFENUM
 where TBS059.NFEDATENT >= '20150701'
 group by NFECFOP

select NFSCFOP,count(*)
  from TBS0671 (nolock) join TBS067 (nolock)
    on TBS0671.NFSEMPCOD=TBS067.NFSEMPCOD and TBS0671.SNESER=TBS067.SNESER and TBS0671.NFSNUM=TBS067.NFSNUM
 where TBS067.NFSDATEMI >= '20150701'
 group by NFSCFOP
