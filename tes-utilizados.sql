  from TBS0671 (nolock) join TBS067 (nolock) on TBS0671.NFSEMPCOD=TBS067.NFSEMPCOD and TBS0671.SNEEMPCOD=TBS067.SNEEMPCOD and TBS0671.SNESER=TBS067.SNESER and
