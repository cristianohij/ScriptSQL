select TBS0671.NFSNUM,NFSDATEMI,NFSCLICOD,NFSCLINOM,VENCOD,NFSITE,PROCOD,NFSPRODES,NFSUNI,
       str(NFSQTDEMB,4,0) as 'NFSQTDEMB',str((NFSQTD-NFSQTDDEV),6,2) as 'NFSQTD',NFSMOVEST,str(NFSPRE,9,2) as 'NFSPRE',
       str((NFSQTD-NFSQTDDEV)*NFSPRE,9,2) as 'NFSTOTITE'
  from TBS0671 join TBS067 on TBS0671.NFSNUM=TBS067.NFSNUM
               join TBS042 on TBS0671.TESCOD=TBS042.TESCOD
 where TBS067.NFSDATEMI between '2000-01-01' and '2009-03-31' and TBS067.NFSCAN='N' and
       TBS0671.PROCOD between '653' and '6539999' and NFSQTD-NFSQTDDEV>0 and TESCNTVEN='S'
        