select TBS0671.PROCOD as 'cod_produto',
       isnull(TBS0521.TDCPROCLI,'') as 'cod_pro_cliente',
       TBS0671.NFSPRODES as 'des_produto',
       TBS010.PROUM1 as 'um',
       TBS014.MARNOM as 'marca',
       sum(TBS0671.NFSQTD*TBS0671.NFSQTDEMB) as 'qtde_total',
       sum((TBS0671.NFSPRE/TBS0671.NFSQTDEMB-(TBS0671.NFSPRE/TBS0671.NFSQTDEMB*TBS0671.NFSPDDITE/100))*TBS0671.NFSQTD*TBS0671.NFSQTDEMB)/sum(TBS0671.NFSQTD*TBS0671.NFSQTDEMB) as 'pre_unitario',
       sum((TBS0671.NFSPRE/TBS0671.NFSQTDEMB-(TBS0671.NFSPRE/TBS0671.NFSQTDEMB*TBS0671.NFSPDDITE/100))*TBS0671.NFSQTD*TBS0671.NFSQTDEMB) as 'val_total'
  from TBS067 (nolock) join TBS0671 (nolock) on TBS067.NFSNUM=TBS0671.NFSNUM
                       join TBS010 (nolock) on TBS010.PROCOD=TBS0671.PROCOD
                       join TBS042 (nolock) on TBS042.TESCOD=TBS0671.TESCOD
                       join TBS014 (nolock) on TBS014.MARCOD=TBS010.MARCOD
                       Left join TBS0521 (nolock) on TBS0521.TDCCLICOD=82 and TBS0521.PROCOD=TBS0671.PROCOD
 where TBS067.NFSDATEMI >= '20100802' and
       TBS067.NFSDATEMI <= '20100807' and
       TBS067.NFSCAN = 'N' and
       TBS067.NFSCLICOD > 0 and
       TBS067.VENCOD > 0 and
       TBS0671.PROCOD >= '164' and
       TBS0671.PROCOD <= '164Z' and
       TBS010.FORCOD > 0 and
       TBS010.MARCOD > 0 and
       TBS042.TESCNTVEN = 'S'
 group by TBS0671.PROCOD,TBS014.MARNOM,TBS010.PROUM1,TBS0671.NFSPRODES,TBS0521.TDCPROCLI
 order by TBS0671.PROCOD
       
       
