select TBS067.NFSCAN,TBS0671.NFSNUM,NFSCLICOD,NFSCLINOM,TBS0671.PROCOD,NFSPRODES,NFSQTD,NFSUNI,isnull(NFENUM,0),
       TBS067.VENCOD,isnull(TBS004.VENNOM,'')
  from TBS067 Left join TBS004 on TBS067.VENCOD=TBS004.VENCOD
              join TBS0671 on TBS067.NFSNUM=TBS0671.NFSNUM
              Left join TBS0591 on TBS0671.NFSNUM=TBS0591.NFENFSNUM and NFETIP='D'
 where TBS0671.PROCOD between '394' and '3949999'
 order by TBS0671.PROCOD